    /// <summary>Escoge referencias coherentes para los casos específicos del lote,
    /// sin reemplazar la confirmación de versión/motor de un presupuesto real.</summary>
    public static Perfil Elegir(int indice, int familia)
    {
        string[]? permitidos = familia switch
        {
            3 => ["Palio", "Gol", "Logan"],
            7 => ["Palio", "Gol", "Clio", "Logan"],
            8 => ["Palio", "Uno", "Clio"],
            10 => ["Logan", "Sandero"],
            11 => ["Palio", "Cronos", "Focus", "Fiesta"],
            12 => ["Hilux", "Ranger", "Frontier", "Amarok", "S10", "D-Max"],
            _ => null
        };
        var opciones = permitidos is null ? Perfiles : Perfiles.Where(p => permitidos.Contains(p.Modelo)).ToArray();
        return opciones[indice % opciones.Count];
    }

    public static async Task CargarAsync(TallerDbContext db)
    {
        if (!db.Database.IsSqlServer() || !db.Database.GetDbConnection().Database.EndsWith("_Demo", StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("El catálogo académico de vehículos requiere una base _Demo.");
        var marcas = await db.Marcas.Include(m => m.Modelos).ToListAsync();
        foreach (var grupo in Entradas.GroupBy(e => e.Marca))
        {
            var marca = marcas.SingleOrDefault(m => m.Nombre == grupo.Key);
            if (marca is null)
            {
                marca = new Marca { Nombre = grupo.Key, Activo = true };
                db.Marcas.Add(marca);
                marcas.Add(marca);
            }
            foreach (var entrada in grupo)
                if (!marca.Modelos.Any(m => m.Nombre == entrada.Modelo))
                    marca.Modelos.Add(new Modelo { Nombre = entrada.Modelo, Activo = true });
        }
        db.Marcas.Add(new Marca { Nombre = "Marca histórica de prueba", Activo = false,
            Modelos = [new Modelo { Nombre = "Modelo fuera de oferta", Activo = false }] });
        await db.SaveChangesAsync();
        db.ChangeTracker.Clear();
    }
