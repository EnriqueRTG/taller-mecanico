INSERT dbo.Categorias (Nombre, Activo)
SELECT DISTINCT origen.Categoria, 1
FROM @Conceptos origen
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.Categorias destino WITH (UPDLOCK, HOLDLOCK)
    WHERE destino.Nombre = origen.Categoria
);

INSERT dbo.Conceptos (IdCategoria, Tipo, Nombre, Descripcion, PrecioReferencia, Activo)
SELECT categoria.IdCategoria, origen.Tipo, origen.Nombre, origen.Descripcion, origen.PrecioReferencia, 1
FROM @Conceptos origen
JOIN dbo.Categorias categoria ON categoria.Nombre = origen.Categoria
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.Conceptos destino WITH (UPDLOCK, HOLDLOCK)
    WHERE destino.IdCategoria = categoria.IdCategoria
      AND destino.Tipo = origen.Tipo AND destino.Nombre = origen.Nombre
);

INSERT dbo.Marcas (Nombre, Activo)
SELECT DISTINCT origen.Marca, 1
FROM @Vehiculos origen
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.Marcas destino WITH (UPDLOCK, HOLDLOCK)
    WHERE destino.Nombre = origen.Marca
);

INSERT dbo.Modelos (IdMarca, Nombre, Activo)
SELECT marca.IdMarca, origen.Modelo, 1
FROM @Vehiculos origen
JOIN dbo.Marcas marca ON marca.Nombre = origen.Marca
WHERE NOT EXISTS (
    SELECT 1 FROM dbo.Modelos destino WITH (UPDLOCK, HOLDLOCK)
    WHERE destino.IdMarca = marca.IdMarca AND destino.Nombre = origen.Modelo
);

